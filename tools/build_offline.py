"""Generate the public offline asset list and revision after building the library."""
import hashlib
import json
from pathlib import Path
from build_library import ROOT, build

def main():
    urls = ["/", "/static/app.css", "/static/app.js", "/static/charts.js", "/static/config.js", "/static/platform.js",
            "/static/manifest.webmanifest", "/static/vendor/uPlot.min.css", "/static/vendor/uPlot.iife.min.js",
            "/static/icons/icon-192.png", "/static/icons/icon-512.png", "/static/icons/apple-touch-icon.png", *build()]
    revision = hashlib.sha256()
    for url in urls:
        path = ROOT / "printer/app/static" / ("index.html" if url == "/" else url.removeprefix("/static/"))
        revision.update(url.encode()); revision.update(path.read_bytes())
    out = ROOT / "printer/app/static/offline-assets.js"
    out.write_text("// Generated by tools/build_offline.py; public assets only.\nself.RETIREMENT_OFFLINE = " +
                   json.dumps({"version": revision.hexdigest()[:16], "urls": urls}, indent=2) + ";\n")
    print(f"Offline bundle: {len(urls)} public assets; revision {revision.hexdigest()[:16]}")

if __name__ == "__main__": main()
